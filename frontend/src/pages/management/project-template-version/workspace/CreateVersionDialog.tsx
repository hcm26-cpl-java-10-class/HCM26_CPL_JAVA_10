import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import type { ProjectTemplateVersionDTO } from "@/types";
import { ArrowRight, CopyPlus, Loader2 } from "lucide-react";
import { nextVersionLabel, versionLabel } from "./version.constants";

interface CreateVersionDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  /** Version the new one will be derived from. */
  source: ProjectTemplateVersionDTO | null;
  /** Every known version, used to preview the next label. */
  versions: ProjectTemplateVersionDTO[];
  loading?: boolean;
  onConfirm: () => void | Promise<void>;
}

/**
 * Confirmation of the "Create New Version" action (US-07 / AC01).
 * <p>
 * The version label is generated by the backend; the dialog only explains what
 * will happen: the configuration is copied, the new row is stored as `DRAFT`
 * and `parentTemplateId` keeps pointing at the source version so the history
 * stays traceable.
 */
export function CreateVersionDialog({
  open,
  onOpenChange,
  source,
  versions,
  loading = false,
  onConfirm,
}: CreateVersionDialogProps) {
  const nextLabel = nextVersionLabel(versions, source?.templateId ?? null);

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-md">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <span className="flex h-10 w-10 items-center justify-center rounded-full bg-primary/10">
              <CopyPlus className="h-5 w-5 text-primary" />
            </span>
            Create New Version
          </DialogTitle>
          <DialogDescription className="pt-2">
            {source ? (
              <>
                A new version of this Project Template will be created from{" "}
                <span className="font-semibold text-foreground">
                  {versionLabel(source)}
                </span>
                .
              </>
            ) : (
              <>
                The first version of this Project Template will be created from
                its current configuration.
              </>
            )}
          </DialogDescription>
        </DialogHeader>

        <div className="flex flex-col gap-3 text-xs text-muted-foreground">
          <div className="flex items-center justify-center gap-2 rounded-lg border bg-muted/40 px-3 py-2">
            <span className="rounded-md bg-background px-2 py-0.5 font-semibold text-foreground ring-1 ring-border">
              {source?.version ?? "—"}
            </span>
            <ArrowRight className="h-3.5 w-3.5" />
            <span className="rounded-md bg-primary/10 px-2 py-0.5 font-semibold text-primary">
              {nextLabel || "—"}
            </span>
          </div>

          <ul className="list-disc space-y-1 pl-5">
            <li>The version number is increased automatically.</li>
            <li>
              The whole configuration is copied into the new version, which
              starts as <span className="font-semibold text-foreground">DRAFT</span>.
            </li>
            <li>
              <span className="font-semibold text-foreground">Parent Version ID</span>{" "}
              {source
                ? <>will point at {versionLabel(source)} for traceability.</>
                : <>stays empty because this is the first version.</>}
            </li>
            <li>
              Workspaces and projects already created from the older version are
              not affected.
            </li>
          </ul>
        </div>

        <DialogFooter>
          <div className="flex w-full justify-between">
            <Button
              variant="outline"
              onClick={() => onOpenChange(false)}
              disabled={loading}
            >
              Cancel
            </Button>
            <Button onClick={onConfirm} disabled={loading}>
              {loading ? (
                <>
                  <Loader2 className="mr-2 h-4 w-4 animate-spin" />
                  Creating...
                </>
              ) : (
                <>
                  <CopyPlus className="mr-2 h-4 w-4" />
                  Create {nextLabel || "version"}
                </>
              )}
            </Button>
          </div>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
