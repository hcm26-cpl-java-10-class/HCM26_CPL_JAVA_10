export type IconKey = keyof typeof iconMap

const toTitle = (key: string) =>
    key
        .replace(/[_-]+/g, " ")
        .replace(/\b\w/g, (c) => c.toUpperCase())

export const iconKeyOptions: Array<{ label: string; value: IconKey }> = Object
    .keys(iconMap)
    .map((key) => ({
        value: key as IconKey,
        label: `${toTitle(key)} (${key})`,
    }))
    .sort((a, b) => a.value.localeCompare(b.value))
