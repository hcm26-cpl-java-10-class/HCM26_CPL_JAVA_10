package com.example.starter_project_2025.system.project.template.config.assignment;

import com.example.starter_project_2025.system.project.ProjectTeamStatus;
import com.example.starter_project_2025.system.project.TeamAllocationSessionStatus;
import com.example.starter_project_2025.system.project.domain.ProjectStatus;
import com.example.starter_project_2025.system.project.milestone.domain.Milestone;
import com.example.starter_project_2025.system.project.milestone.domain.MilestoneLifecycleStatus;
import com.example.starter_project_2025.system.project.milestone.domain.MilestoneStatus;
import com.example.starter_project_2025.system.project.milestone.integration.port.TenantSettingsPort;
import com.example.starter_project_2025.system.project.milestone.repository.MilestoneRepository;
import com.example.starter_project_2025.system.project.milestone.submission.domain.MilestoneExecutionStatus;
import com.example.starter_project_2025.system.project.milestone.submission.domain.SubmissionStatus;
import com.example.starter_project_2025.system.project.project_template_version.ProjectTemplateSnapshotRepository;
import com.example.starter_project_2025.system.project.template.service.assignment.TemplateBriefSnapshotWriter;
import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.persistence.EntityManager;
import jakarta.persistence.Tuple;
import java.nio.charset.StandardCharsets;
import java.time.Clock;
import java.time.Instant;
import java.time.LocalDate;
import java.time.temporal.ChronoUnit;
import java.util.List;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

/** Restores the original publication start of milestones generated by earlier template provisioning. */
@Slf4j
@Component
@RequiredArgsConstructor
public class PublishedTemplateMilestoneBackfill implements ApplicationRunner {
    private final EntityManager entityManager;
    private final MilestoneRepository milestones;
    private final ProjectTemplateSnapshotRepository snapshots;
    private final TenantSettingsPort tenantSettings;
    private final ObjectMapper json;
    private final Clock milestoneClock;

    @Override
    @Transactional
    public void run(ApplicationArguments args) {
        Instant now = milestoneClock.instant();
        int restored = 0;
        for (Tuple candidate : candidates()) {
            var milestone = milestones.lockForProjectOpen(candidate.get("milestoneId", UUID.class),
                    candidate.get("projectId", Long.class), candidate.get("tenantId", Long.class)).orElse(null);
            if (milestone == null || milestone.lifecycleStatus() != MilestoneLifecycleStatus.PLANNED
                    || milestone.isAutoStartEnabled() || milestone.scheduledStartAt() != null
                    || milestone.getStartDate() != null) continue;

            Instant publishedAt = originalPublication(candidate, milestone);
            if (publishedAt == null || now.isBefore(publishedAt)) continue;
            LocalDate startDate = LocalDate.ofInstant(publishedAt, tenantSettings.requireTimeZone(milestone.getTenantId()));
            milestone.scheduleStart(startDate, publishedAt);
            milestone.startAutomatically(now);
            restored++;
        }
        if (restored > 0) log.info("Restored the publication start of {} template milestones", restored);
    }

    private List<Tuple> candidates() {
        return entityManager.createQuery("""
                select m.id as milestoneId, m.projectId as projectId, m.tenantId as tenantId,
                       p.assignmentId as assignmentId, p.createdBy as projectCreator, s.id as snapshotId,
                       a.assignedAt as assignedAt, a.createdBy as assigner
                  from Milestone m
                  join Project p on p.id = m.projectId and p.tenantId = m.tenantId
                  join ProjectTemplateSnapshot s on s.id = p.templateSnapshotId and s.projectId = p.id
                  left join ProjectAssignment a on a.id = p.assignmentId and a.tenantId = p.tenantId
                  left join TeamAllocationSession allocation on allocation.id = a.sessionId
                 where p.isActive = true and p.status = :activeProject and m.active = true
                   and m.scheduledStartAt is null and m.startDate is null and m.autoStartEnabled = false
                   and (m.lifecycleState is null or m.lifecycleState = :planned)
                   and ((m.status = :draftMilestone and (m.executionStatus is null or m.executionStatus = :todo))
                         or (m.status = :openMilestone and m.executionStatus = :todo))
                   and (
                       (a.isActive = true and a.masterProjectId is not null and allocation.status = :publishedSession)
                       or (p.assignmentId is null and exists (
                           select 1 from ProjectTeam team
                            where team.id = m.teamId and team.project.id = p.id
                              and team.isActive = true and team.status = :activeTeam
                       ))
                   )
                   and not exists (
                       select 1 from MilestoneSubmission submission where submission.milestone.id = m.id
                         and (submission.status <> :draftSubmission or submission.submissionAttempts > 0)
                   )
                   and not exists (select 1 from MilestoneWaiver waiver where waiver.milestoneId = m.id)
                 order by m.id
                """, Tuple.class)
                .setParameter("activeProject", ProjectStatus.ACTIVE)
                .setParameter("planned", MilestoneLifecycleStatus.PLANNED)
                .setParameter("draftMilestone", MilestoneStatus.PLANNED)
                .setParameter("openMilestone", MilestoneStatus.OPEN)
                .setParameter("todo", MilestoneExecutionStatus.TODO)
                .setParameter("publishedSession", TeamAllocationSessionStatus.PUBLISHED)
                .setParameter("activeTeam", ProjectTeamStatus.ACTIVE)
                .setParameter("draftSubmission", SubmissionStatus.DRAFT)
                .getResultList();
    }

    private Instant originalPublication(Tuple candidate, Milestone milestone) {
        if (candidate.get("assignmentId", Long.class) != null) {
            Instant assignedAt = candidate.get("assignedAt", Instant.class);
            // The hierarchy writer stamps each generated milestone with the assignment time and actor.
            return milestone.getCreatedAt().equals(assignedAt)
                    && createdBy(milestone, "project-assignment:", candidate.get("assigner", Long.class))
                    ? assignedAt : null;
        }
        // Standalone provisioning uses the user's actor ID and stamps the creation time before copying the template.
        if (!createdBy(milestone, "user:", candidate.get("projectCreator", Long.class))) return null;
        return snapshots.findById(candidate.get("snapshotId", Long.class))
                .filter(snapshot -> matchesFrozenPlan(snapshot.getContentJson(), milestone))
                .map(snapshot -> milestone.getCreatedAt()).orElse(null);
    }

    private boolean createdBy(Milestone milestone, String prefix, Long userId) {
        return userId != null && UUID.nameUUIDFromBytes((prefix + userId).getBytes(StandardCharsets.UTF_8))
                .equals(milestone.getCreatedBy());
    }

    private boolean matchesFrozenPlan(String content, Milestone milestone) {
        if (content == null || milestone.getTeamId() == null || milestone.getRubricSnapshotId() == null) return false;
        try {
            JsonNode snapshot = json.readTree(content);
            if (snapshot == null || !TemplateBriefSnapshotWriter.PURPOSE_TEAM_ASSIGNMENT.equals(snapshot.path("purpose").asText())
                    || snapshot.path("assignedTeamId").asLong(-1) != milestone.getTeamId()) return false;
            for (JsonNode item : snapshot.path("milestones")) {
                long days = item.path("dueAfter").asInt(-1) * ("WEEKS".equals(item.path("dueUnit").asText()) ? 7L : 1L);
                if (days > 0 && milestone.getTitle().equals(item.path("title").asText())
                        && milestone.getRubricSnapshotId().toString().equalsIgnoreCase(item.path("rubricVersionId").asText())
                        && milestone.getCreatedAt().plus(days, ChronoUnit.DAYS).equals(milestone.getDeadline())) return true;
            }
        } catch (JsonProcessingException invalidSnapshot) {
            return false;
        }
        return false;
    }
}
