package com.example.starter_project_2025.system.project.project_template_version;

import com.example.starter_project_2025.base.crud.controller.BaseCrudDataIoController;
import com.example.starter_project_2025.base.crud.domain.BaseCrudRepository;
import com.example.starter_project_2025.base.crud.service.BaseCrudService;
import com.example.starter_project_2025.base.dataio.common.FileFormat;
import com.example.starter_project_2025.base.dataio.importer.result.ImportResult;
import com.example.starter_project_2025.exception.error.ErrorResponse;
import com.example.starter_project_2025.exception.error.ValidationErrorResponse;
import com.example.starter_project_2025.system.project.project_template_version.audit.ProjectTemplateSnapshotAuditLogDTO;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.servlet.http.HttpServletResponse;
import lombok.AccessLevel;
import lombok.RequiredArgsConstructor;
import lombok.experimental.FieldDefaults;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.time.LocalDateTime;
import java.util.List;

@RestController
@RequiredArgsConstructor
@RequestMapping("/api/project-template-versions")
@FieldDefaults(level = AccessLevel.PRIVATE, makeFinal = true)
@Tag(name = "Project Template Version", description = "APIs for managing project template versions (snapshots)")
public class ProjectTemplateSnapshotController
        extends BaseCrudDataIoController<
        ProjectTemplateSnapshot,
        Long,
        ProjectTemplateSnapshotDTO,
        ProjectTemplateSnapshotFilter> {

    ProjectTemplateSnapshotService snapshotService;
    ProjectTemplateSnapshotRepository snapshotRepository;

    @Override
    protected BaseCrudService<Long, ProjectTemplateSnapshotDTO, ProjectTemplateSnapshotFilter> getService() {
        return snapshotService;
    }

    @Override
    protected BaseCrudRepository<ProjectTemplateSnapshot, Long> getRepository() {
        return snapshotRepository;
    }

    @Override
    protected Class<ProjectTemplateSnapshot> getEntityClass() {
        return ProjectTemplateSnapshot.class;
    }

    /**
     * Every version of a project template, newest first.
     */
    @GetMapping("/by-template/{templateId}")
    public ResponseEntity<List<ProjectTemplateSnapshotDTO>> getByTemplate(
            @PathVariable Long templateId) {
        return ResponseEntity.ok(snapshotService.getByTemplate(templateId));
    }

    /**
     * US-07: creates the next version from an existing one.
     * <p>
     * The version label is generated by the server ({@code v1.0 -> v2.0}), the
     * configuration is copied, {@code parentTemplateId} points at the source
     * version and the new row is stored as {@code DRAFT}. The source snapshot is
     * never modified, so workspaces/projects already created from it keep their
     * own copy of the data.
     */
    @PostMapping("/{id}/new-version")
    @PreAuthorize("hasAuthority('PROJECT_TEMPLATE_VERSION_CREATE')")
    public ResponseEntity<ProjectTemplateSnapshotDTO> createNewVersion(
            @PathVariable Long id) {
        return ResponseEntity.status(HttpStatus.CREATED)
                .body(snapshotService.createNewVersion(id));
    }

    /**
     * US-08: duplicates the template behind the given version into a brand new,
     * fully independent Project Template.
     * <p>
     * The client supplies the new {@code code} (must be unique) and {@code name};
     * the server copies the configuration (rules, milestones, rubric), stores the
     * row as {@code v1.0} / {@code DRAFT} and leaves {@code parentTemplateId}
     * empty, so the copy keeps no version-tree link to the source template. The
     * source template and its versions are never modified.
     */
    @PostMapping("/{id}/duplicate")
    @PreAuthorize("hasAuthority('PROJECT_TEMPLATE_VERSION_CREATE')")
    public ResponseEntity<ProjectTemplateSnapshotDTO> duplicate(
            @PathVariable Long id,
            @RequestBody(required = false) DuplicateProjectTemplateRequest request) {

        DuplicateProjectTemplateRequest payload = request != null
                ? request
                : new DuplicateProjectTemplateRequest();

        return ResponseEntity.status(HttpStatus.CREATED)
                .body(snapshotService.duplicateTemplate(id, payload.getCode(), payload.getName()));
    }

    /**
     * Audit trail of a snapshot (actor, timestamp, before/after state,
     * correlation id).
     */
    @GetMapping("/{id}/audit-logs")
    public ResponseEntity<List<ProjectTemplateSnapshotAuditLogDTO>> getAuditLogs(
            @PathVariable Long id) {
        return ResponseEntity.ok(snapshotService.getAuditLogs(id));
    }

    /**
     * Export uses flattened rows so the exported headers match the import
     * template of the module.
     */
    @Override
    @GetMapping("/export")
    @PreAuthorize("hasAuthority('PROJECT_TEMPLATE_VERSION_READ')")
    public void exportFile(
            @RequestParam(defaultValue = "EXCEL") FileFormat format,
            HttpServletResponse response
    ) throws IOException {
        exportService.export(
                format,
                snapshotService.getExportRows(),
                ProjectTemplateSnapshotExportRow.class,
                response);
    }

    /**
     * Import requires the create permission of the resource.
     */
    @Override
    @PostMapping(value = "/import", consumes = "multipart/form-data")
    @PreAuthorize("hasAuthority('PROJECT_TEMPLATE_VERSION_CREATE')")
    public ImportResult importFile(@RequestParam("file") MultipartFile file) {
        return super.importFile(file);
    }

    // ---------------------------------------------------------------------
    // Use-case specific error mapping (kept local to the module so the global
    // handler contract used by other modules is untouched).
    // ---------------------------------------------------------------------

    @ExceptionHandler(ProjectTemplateSnapshotValidationException.class)
    public ResponseEntity<ValidationErrorResponse> handleSnapshotValidation(
            ProjectTemplateSnapshotValidationException ex) {
        ValidationErrorResponse body =
                new ValidationErrorResponse("Dữ liệu không hợp lệ", ex.getErrors());
        return ResponseEntity.status(HttpStatus.UNPROCESSABLE_ENTITY).body(body);
    }

    @ExceptionHandler(ProjectTemplateSnapshotConflictException.class)
    public ResponseEntity<ErrorResponse> handleSnapshotConflict(
            ProjectTemplateSnapshotConflictException ex) {
        ErrorResponse body = new ErrorResponse(
                HttpStatus.CONFLICT.value(),
                ex.getMessage(),
                LocalDateTime.now()
        );
        return ResponseEntity.status(HttpStatus.CONFLICT).body(body);
    }

    /**
     * Last line of defence for the unique (template, version) constraint when
     * two concurrent requests pass the service-level duplicate check.
     */
    @ExceptionHandler(DataIntegrityViolationException.class)
    public ResponseEntity<ErrorResponse> handleDataIntegrityViolation(
            DataIntegrityViolationException ex) {
        ErrorResponse body = new ErrorResponse(
                HttpStatus.CONFLICT.value(),
                ProjectTemplateSnapshotConflictException.DEFAULT_MESSAGE,
                LocalDateTime.now()
        );
        return ResponseEntity.status(HttpStatus.CONFLICT).body(body);
    }
}
