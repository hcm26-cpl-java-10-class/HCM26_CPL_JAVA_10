package com.example.starter_project_2025.system.demo.course;
import com.example.starter_project_2025.system.demo.section.*;
import com.example.starter_project_2025.system.demo.online_lession.*;
import lombok.RequiredArgsConstructor;
import org.springframework.web.bind.annotation.*;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.http.*;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;
import org.apache.poi.ss.usermodel.*;
import java.util.*;
@RestController @RequestMapping("/api/courses") @RequiredArgsConstructor
public class CourseBundleExportController {
 private final CourseRepository courses; private final SectionRepository sections; private final LessonRepository lessons;
 @GetMapping("/export-bundle") @PreAuthorize("hasAuthority('COURSE_READ')") @Transactional(readOnly=true)
 public ResponseEntity<byte[]> export() throws java.io.IOException {
  try(var workbook=new XSSFWorkbook(); var out=new java.io.ByteArrayOutputStream()) {
   Sheet readme=workbook.createSheet("ReadMe"); row(readme,"Backend Course bundle. Existing records are skipped on import; IDs and timestamps are generated by the backend.");
   row(readme,"Lessons without a Section are exported with blank Section Title; assign a valid Section Title before reimporting them.");
   Sheet cs=workbook.createSheet("Courses");row(cs,"Name","Description","Instructor","Thumbnail URL","Status","Level","Active","Instructor Email","Category Codes");
   Sheet ss=workbook.createSheet("Sections");row(ss,"Course Name","Section Title","Order Index","Active");
   Sheet ls=workbook.createSheet("Lessons");row(ls,"Course Name","Section Title","Lesson Title","Content Type","Content URL","Text Content","Duration (seconds)","Order Index","Active");
   for(Course c:courses.findAll()) {
    row(cs,c.getName(),c.getDescription(),c.getInstructor(),c.getThumbnailUrl(),c.getPublicationStatus(),c.getCourseLevel(),c.getIsActive(),c.getInstructorEmail(),c.getCategory());
    for(Section s:sections.findByCourse_IdOrderByOrderIndexAsc(c.getId())) {
     row(ss,c.getName(),s.getTitle(),s.getOrderIndex(),s.getIsActive());
     for(Lesson l:lessons.findBySection_IdOrderByOrderIndexAsc(s.getId())) row(ls,c.getName(),s.getTitle(),l.getTitle(),l.getContentType(),l.getContentUrl()!=null?l.getContentUrl():l.getVideoUrl(),l.getTextContent(),l.getDurationSeconds()!=null?l.getDurationSeconds():l.getDurationMinutes()==null?null:l.getDurationMinutes()*60,l.getOrderIndex(),l.getIsActive());
    }
    for(Lesson l:lessons.findAllByCourse_IdOrderByOrderIndexAsc(c.getId())) if(l.getSection()==null)row(ls,c.getName(),"",l.getTitle(),l.getContentType(),l.getContentUrl()!=null?l.getContentUrl():l.getVideoUrl(),l.getTextContent(),l.getDurationSeconds()!=null?l.getDurationSeconds():l.getDurationMinutes()==null?null:l.getDurationMinutes()*60,l.getOrderIndex(),l.getIsActive());
   }
   workbook.write(out);return ResponseEntity.ok().header(HttpHeaders.CONTENT_DISPOSITION,"attachment; filename=course-bundle.xlsx").contentType(MediaType.parseMediaType("application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")).body(out.toByteArray());
  }
 }
 private void row(Sheet sheet,Object... values) {Row row=sheet.createRow(sheet.getPhysicalNumberOfRows());for(int i=0;i<values.length;i++){Cell cell=row.createCell(i);Object v=values[i];if(v instanceof Boolean b)cell.setCellValue(b);else if(v instanceof Number n)cell.setCellValue(n.doubleValue());else cell.setCellValue(v==null?"":v.toString());}}
}
