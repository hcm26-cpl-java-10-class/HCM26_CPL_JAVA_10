package com.example.starter_project_2025.system.project.developmentinsights.service;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.Statement;
import javax.sql.DataSource;
import lombok.RequiredArgsConstructor;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.annotation.Order;
import org.springframework.stereotype.Component;

/** Creates only Git Activity-owned tables when the application is configured with H2 schema management off. */
@Component
@Order(Integer.MIN_VALUE + 20)
@RequiredArgsConstructor
public class GitDevelopmentRuleSchemaInitializer implements ApplicationRunner {
    private final DataSource dataSource;

    @Override
    public void run(ApplicationArguments args) throws Exception {
        try (Connection connection = dataSource.getConnection()) {
            DatabaseMetaData metadata = connection.getMetaData();
            if (!"H2".equalsIgnoreCase(metadata.getDatabaseProductName())) return;
            try (Statement statement = connection.createStatement()) {
                statement.execute("""
                        CREATE TABLE IF NOT EXISTS project_dev_rule (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            project_id BIGINT NOT NULL,
                            rule_type VARCHAR(32) NOT NULL,
                            version INTEGER NOT NULL,
                            enabled BOOLEAN NOT NULL,
                            allowed_commit_types VARCHAR(160) NOT NULL,
                            scope_required BOOLEAN NOT NULL,
                            task_key_pattern VARCHAR(160) NOT NULL,
                            created_by BIGINT,
                            created_at TIMESTAMP WITH TIME ZONE NOT NULL,
                            CONSTRAINT uk_git_dev_rule_root_type_version UNIQUE (project_id, rule_type, version),
                            CONSTRAINT fk_git_dev_rule_project FOREIGN KEY (project_id) REFERENCES projects(id),
                            CONSTRAINT fk_git_dev_rule_user FOREIGN KEY (created_by) REFERENCES users(id)
                        )
                        """);
                statement.execute("CREATE INDEX IF NOT EXISTS idx_git_dev_rule_root_type_version ON project_dev_rule(project_id, rule_type, version)");
                statement.execute("""
                        CREATE TABLE IF NOT EXISTS commit_validation_result (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            commit_id BIGINT NOT NULL,
                            rule_type VARCHAR(32) NOT NULL,
                            rule_version INTEGER NOT NULL,
                            evaluation_key VARCHAR(48) DEFAULT 'INGESTION' NOT NULL,
                            rule_snapshot CLOB,
                            status VARCHAR(24) NOT NULL,
                            reason VARCHAR(1000),
                            details CLOB,
                            evaluated_at TIMESTAMP WITH TIME ZONE NOT NULL,
                            CONSTRAINT uk_git_validation_commit_rule_run UNIQUE (commit_id, rule_type, rule_version, evaluation_key),
                            CONSTRAINT fk_git_validation_commit FOREIGN KEY (commit_id) REFERENCES git_commit(id) ON DELETE CASCADE
                        )
                        """);
                statement.execute("CREATE INDEX IF NOT EXISTS idx_git_validation_commit_rule_latest ON commit_validation_result(commit_id, rule_type, evaluated_at)");
                statement.execute("""
                        CREATE TABLE IF NOT EXISTS commit_validation_task_reference (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            validation_result_id BIGINT NOT NULL,
                            task_id BIGINT NOT NULL,
                            project_id BIGINT NOT NULL,
                            CONSTRAINT uk_git_validation_task_reference UNIQUE (validation_result_id, task_id),
                            CONSTRAINT fk_git_validation_task_result FOREIGN KEY (validation_result_id) REFERENCES commit_validation_result(id) ON DELETE CASCADE,
                            CONSTRAINT fk_git_validation_task_backlog FOREIGN KEY (task_id) REFERENCES sprint_backlog(sprint_backlog_id) ON DELETE CASCADE,
                            CONSTRAINT fk_git_validation_task_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
                        )
                        """);
                statement.execute("CREATE INDEX IF NOT EXISTS idx_git_validation_task_result ON commit_validation_task_reference(validation_result_id)");
            }
        }
    }
}
