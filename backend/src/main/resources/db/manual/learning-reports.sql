create table if not exists personal_learning_reports (
    id bigint generated by default as identity primary key,
    owner_id bigint not null references users(id) on delete cascade,
    request_key varchar(36) not null,
    request_fingerprint varchar(64) not null,
    title varchar(150) not null,
    type varchar(255) not null,
    period_start date not null,
    period_end date not null,
    period_to_date boolean not null,
    zone varchar(80) not null,
    mode varchar(255) not null,
    language varchar(255) not null,
    sections varchar(150) not null,
    generated_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    schema_version integer not null,
    snapshot_json text not null,
    analysis_json text,
    ai_status varchar(255) not null,
    analysis_started_at timestamp with time zone,
    retryable boolean not null,
    unique (owner_id, request_key)
);
create index if not exists ix_personal_report_owner_date on personal_learning_reports(owner_id, generated_at);
