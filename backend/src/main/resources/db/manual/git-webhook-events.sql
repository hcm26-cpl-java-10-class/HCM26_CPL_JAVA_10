-- US-SY-03 additive deployment script for MySQL 8. No existing data is updated; safe to run twice.
-- Deployments with ddl-auto=validate/none must apply this before deploying GitHub webhooks.
CREATE TABLE IF NOT EXISTS git_webhook_events (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    is_active BOOLEAN NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    created_by BIGINT,
    updated_by BIGINT,
    provider VARCHAR(20) NOT NULL,
    delivery_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    action VARCHAR(50),
    hook_id BIGINT,
    installation_id BIGINT,
    repo_external_id BIGINT,
    repo_full_name VARCHAR(200),
    sender_login VARCHAR(100),
    tenant_id BIGINT,
    installation_ref BIGINT,
    repository_ref BIGINT,
    payload LONGTEXT,
    payload_bytes INT NOT NULL,
    payload_purged_at DATETIME(6),
    status VARCHAR(20) NOT NULL,
    attempts INT NOT NULL,
    next_attempt_at DATETIME(6) NOT NULL,
    last_error VARCHAR(1000),
    received_at DATETIME(6) NOT NULL,
    processing_started_at DATETIME(6),
    processed_at DATETIME(6),
    version BIGINT,
    CONSTRAINT uk_git_webhook_delivery UNIQUE (provider, delivery_id),
    INDEX idx_git_webhook_due (status, next_attempt_at),
    INDEX idx_git_webhook_installation (installation_id, received_at),
    INDEX idx_git_webhook_repository (repo_external_id, received_at),
    INDEX idx_git_webhook_received (received_at)
);
