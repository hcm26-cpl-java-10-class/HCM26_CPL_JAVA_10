-- Apply before deployment if Hibernate schema updates are disabled.
create table if not exists habit_goals (
    id bigint generated by default as identity primary key,
    owner_id bigint not null references users(id) on delete cascade,
    version bigint not null,
    period varchar(255) not null,
    title varchar(150) not null,
    description varchar(2000),
    target_minutes integer not null check (target_minutes > 0),
    start_date date not null,
    end_date date,
    archived_on date,
    history_from date not null
);
create index if not exists ix_habit_goal_owner on habit_goals(owner_id, period);

create table if not exists habit_goal_targets (
    id bigint generated by default as identity primary key,
    owner_id bigint not null references users(id) on delete cascade,
    goal_id bigint not null,
    period varchar(255) not null,
    period_start date not null,
    from_date date not null,
    to_date date not null,
    title varchar(150) not null,
    target_minutes integer not null check (target_minutes > 0),
    unique (owner_id, period, period_start)
);

create table if not exists habit_sessions (
    id bigint generated by default as identity primary key,
    owner_id bigint not null references users(id) on delete cascade,
    version bigint not null,
    active_owner_id bigint unique,
    request_key varchar(36) not null,
    course_id bigint,
    course_name varchar(255),
    title varchar(150) not null,
    notes varchar(2000),
    source varchar(255) not null,
    state varchar(255) not null,
    study_date date not null,
    elapsed_seconds bigint not null check (elapsed_seconds >= 0),
    corrected boolean not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    finished_at timestamp with time zone,
    zone varchar(80) not null,
    deleted boolean not null,
    unique (owner_id, request_key)
);
create index if not exists ix_habit_session_owner on habit_sessions(owner_id, study_date);

create table if not exists habit_session_intervals (
    session_id bigint not null references habit_sessions(id) on delete cascade,
    sequence_no integer not null,
    started_at timestamp with time zone not null,
    stopped_at timestamp with time zone,
    primary key (session_id, sequence_no)
);

create table if not exists habit_objectives (
    id bigint generated by default as identity primary key,
    owner_id bigint not null references users(id) on delete cascade,
    version bigint not null,
    course_id bigint,
    course_name varchar(255),
    title varchar(150) not null,
    description varchar(2000),
    week_start date not null,
    target_date date,
    completed_at timestamp with time zone,
    display_order integer not null
);
create index if not exists ix_habit_objective_owner on habit_objectives(owner_id, week_start);
