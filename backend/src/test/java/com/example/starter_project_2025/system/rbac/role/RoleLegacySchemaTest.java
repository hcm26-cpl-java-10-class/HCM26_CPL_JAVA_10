package com.example.starter_project_2025.system.rbac.role;

import com.example.starter_project_2025.system.rbac.permission.Permission;
import java.sql.DriverManager;
import java.util.UUID;
import org.hibernate.cfg.Configuration;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import static org.assertj.core.api.Assertions.assertThat;

class RoleLegacySchemaTest {
    @ParameterizedTest
    @ValueSource(strings = {"", ";MODE=MySQL"})
    void schemaUpdateAddsSystemFlagWithoutLosingExistingRoles(String mode) throws Exception {
        String url = "jdbc:h2:mem:role-legacy-" + UUID.randomUUID() + mode;
        // Keep this connection open so Hibernate updates the same populated database.
        try (var connection = DriverManager.getConnection(url, "sa", "");
             var statement = connection.createStatement()) {
            statement.execute("create table roles (id bigint generated by default as identity primary key,"
                + "name varchar(100) not null unique, description varchar(255), is_active boolean not null default true,"
                + "created_at timestamp not null, updated_at timestamp not null,"
                + "created_by bigint, updated_by bigint)");
            statement.execute("insert into roles(name,description,created_at,updated_at)"
                + " values ('ADMIN','Existing administrator',current_timestamp,current_timestamp)");
            var config = new Configuration()
                .setPhysicalNamingStrategy(new org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy())
                .addAnnotatedClass(Role.class)
                .addAnnotatedClass(Permission.class)
                .setProperty("hibernate.connection.url", url)
                .setProperty("hibernate.connection.username", "sa")
                .setProperty("hibernate.connection.password", "")
                .setProperty("hibernate.hbm2ddl.auto", "update")
                .setProperty("hibernate.hbm2ddl.halt_on_error", "true");
            // Run twice to verify restart does not reset an existing flag.
            try (var factory = config.buildSessionFactory()) {
                try (var rows = statement.executeQuery("select name,description,is_system,is_active from roles")) {
                    assertThat(rows.next()).isTrue();
                    assertThat(rows.getString("name")).isEqualTo("ADMIN");
                    assertThat(rows.getString("description")).isEqualTo("Existing administrator");
                    assertThat(rows.getBoolean("is_system")).isFalse();
                    assertThat(rows.getBoolean("is_active")).isTrue();
                    assertThat(rows.next()).isFalse();
                }
                statement.executeUpdate("update roles set is_system=true,is_active=false");
            }
            try (var factory = new Configuration()
                     .setPhysicalNamingStrategy(new org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy())
                     .addAnnotatedClass(Role.class).addAnnotatedClass(Permission.class)
                     .setProperty("hibernate.connection.url", url)
                     .setProperty("hibernate.connection.username", "sa")
                     .setProperty("hibernate.connection.password", "")
                     .setProperty("hibernate.hbm2ddl.auto", "update")
                     .setProperty("hibernate.hbm2ddl.halt_on_error", "true").buildSessionFactory();
                 var rows = statement.executeQuery("select is_system,is_active from roles")) {
                assertThat(rows.next()).isTrue();
                assertThat(rows.getBoolean("is_system")).isTrue();
                assertThat(rows.getBoolean("is_active")).isFalse();
            }
        }
    }
}
