/**
 * SY-05 step 0: Task IDs ({@code PREFIX-NUMBER}) generated by the server and stored
 * in {@code sprint_backlog.task_key}.
 */
@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("test")
class BacklogTaskKeyIntegrationTest {

    @Autowired MockMvc mvc;
    @Autowired ObjectMapper json;
    @Autowired TransactionTemplate tx;
    @Autowired JdbcTemplate jdbc;
    @Autowired TenantRepository tenants;
    @Autowired UserRepository users;
    @Autowired RoleRepository roles;
    @Autowired PermissionRepository permissions;
    @Autowired ProjectRepository projects;
    @Autowired ProjectTeamRepository teams;
    @Autowired ProjectMemberRepository memberships;
    @Autowired TrainingClassRepository classes;
    @Autowired ClassMemberRepository classMembers;
    @Autowired TeamAllocationSessionRepository allocationSessions;
    @Autowired WorkspaceRepository workspaces;
    @Autowired SprintBacklogRepository backlogs;
    @Autowired UserDetailsService userDetails;
    @Autowired RefreshTokenService tokens;
    @Autowired BacklogTaskKeyService taskKeys;
    @Autowired TaskKeySequenceAllocator allocator;
    @Autowired BacklogTaskKeyMigration migration;

    Long tenantId;
    Long projectId;
    Long workspaceId;
    String token;

    @BeforeEach
    void fixture() throws Exception {
        tx.executeWithoutResult(status -> {
            Tenant tenant = tenants.saveAndFlush(Tenant.builder()
                    .code("KEY-" + UUID.randomUUID()).name("Task key tenant").build());
            tenantId = tenant.getId();
            Role role = new Role();
            role.setName("KEY-" + UUID.randomUUID());
            role.setPermissions(new HashSet<>(permissions.findAll()));
            roles.saveAndFlush(role);
            User user = new User();
            user.setEmail(UUID.randomUUID() + "@task-key.test");
            user.setFirstName("Task"); user.setLastName("Key");
            user.setUserCode("KEY-" + UUID.randomUUID());
            user.setPasswordHash("unused-test-password");
            user.setTenant(tenant); user.setRoles(new HashSet<>(Set.of(role)));
            Long actorId = users.saveAndFlush(user).getId();
            Project project = new Project();
            project.setCode("KEY-" + UUID.randomUUID()); project.setName("Web Shop");
            project.setTenant(tenant); project.setStatus(ProjectStatus.ACTIVE);
            projectId = projects.saveAndFlush(project).getId();
            TrainingClass trainingClass = new TrainingClass();
            trainingClass.setCode("KEY-" + UUID.randomUUID()); trainingClass.setName("Task key class");
            trainingClass.setTenantId(tenantId); trainingClass.setProgramId(1L);
            trainingClass.setStatus(TrainingClassStatus.ONGOING);
            classes.saveAndFlush(trainingClass);
            TeamAllocationSession session = new TeamAllocationSession();
            session.setTrainingClass(trainingClass); session.setMaxMembers(5);
            session.setStatus(TeamAllocationSessionStatus.PUBLISHED);
            allocationSessions.saveAndFlush(session);
            ClassMember classMember = new ClassMember();
            classMember.setTrainingClass(trainingClass); classMember.setUser(user);
            classMember.setStatus(ClassMemberStatus.ACTIVE);
            classMembers.saveAndFlush(classMember);
            ProjectTeam team = new ProjectTeam();
            team.setTeamName("Team Key"); team.setTrainingClass(trainingClass); team.setAllocationSession(session);
            team.setMaxMembers(5); team.setStatus(ProjectTeamStatus.ACTIVE);
            team.setProject(project); team.setAssignedMentorId(actorId);
            teams.saveAndFlush(team);
            ProjectMember membership = new ProjectMember();
            membership.setTeam(team); membership.setClassMember(classMember);
            memberships.saveAndFlush(membership);
            var principal = userDetails.loadUserByUsername(user.getEmail());
            token = tokens.generateAccessToken(new UsernamePasswordAuthenticationToken(
                    principal, null, principal.getAuthorities()));
            workspaceTeamId = team.getId();
        });
        var created = mvc.perform(post("/api/workspaces")
                        .header("Authorization", "Bearer " + token)
                        .header("X-Idempotency-Key", UUID.randomUUID().toString())
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(json.writeValueAsString(Map.of("teamId", workspaceTeamId, "taskKeyPrefix", "web"))))
                .andExpect(status().isCreated()).andReturn();
        workspaceId = json.readTree(created.getResponse().getContentAsString()).get("id").asLong();
    }

    Long workspaceTeamId;

    JsonNode create(Map<String, Object> body) throws Exception {
        Map<String, Object> payload = new HashMap<>(body);
        payload.putIfAbsent("title", "Item " + UUID.randomUUID());
        payload.putIfAbsent("projectId", projectId);
        payload.putIfAbsent("isActive", true);
        return json.readTree(mvc.perform(post("/api/sprint-backlogs")
                        .header("Authorization", "Bearer " + token).contentType(MediaType.APPLICATION_JSON)
                        .content(json.writeValueAsString(payload)))
                .andExpect(status().is2xxSuccessful())
                .andReturn().getResponse().getContentAsString());
    }

    /** An item saved directly (import / forgotten path): no key yet. */
    Long unkeyedItem() {
        return tx.execute(status -> {
            SprintBacklog item = new SprintBacklog();
            item.setTitle("Saved without key " + UUID.randomUUID());
            item.setProjectId(projectId);
            return backlogs.saveAndFlush(item).getId();
        });
    }

    @Test
    void itemsCreatedInAWorkspaceAreNumberedWithItsPrefix() throws Exception {
        assertThat(create(Map.of()).get("taskKey").asText()).isEqualTo("WEB-1");
        assertThat(create(Map.of()).get("taskKey").asText()).isEqualTo("WEB-2");
        JsonNode third = create(Map.of());
        assertThat(third.get("taskKey").asText()).isEqualTo("WEB-3");

        SprintBacklog stored = backlogs.findById(third.get("id").asLong()).orElseThrow();
        assertThat(stored.getTenantId()).isEqualTo(tenantId);
        assertThat(stored.getTaskKeyNumber()).isEqualTo(3L);
    }

    @Test
    void clientsCanNeitherChooseNorChangeTheKey() throws Exception {
        JsonNode item = create(Map.of("taskKey", "HACK-1"));
        assertThat(item.get("taskKey").asText()).isEqualTo("WEB-1");
        long id = item.get("id").asLong();

        mvc.perform(put("/api/sprint-backlogs/{id}", id)
                        .header("Authorization", "Bearer " + token).contentType(MediaType.APPLICATION_JSON)
                        .content(json.writeValueAsString(Map.of("taskKey", "HACK-2", "title", "Renamed item", "isActive", true))))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.taskKey").value("WEB-1"))
                .andExpect(jsonPath("$.title").value("Renamed item"));
        assertThat(backlogs.findById(id).orElseThrow().getTaskKey()).isEqualTo("WEB-1");
    }

    @Test
    void aDeletedItemKeepsItsNumberAndTheNumberIsNeverReused() throws Exception {
        create(Map.of());
        long second = create(Map.of()).get("id").asLong();
        mvc.perform(delete("/api/sprint-backlogs/{id}", second).header("Authorization", "Bearer " + token))
                .andExpect(status().is2xxSuccessful());

        assertThat(create(Map.of()).get("taskKey").asText()).isEqualTo("WEB-3");
        backlogs.findById(second).ifPresent(deleted -> assertThat(deleted.getTaskKey()).isEqualTo("WEB-2"));
    }

    @Test
    void anItemCanBeFoundByItsKeyInAnyCase() throws Exception {
        long id = create(Map.of()).get("id").asLong();

        mvc.perform(get("/api/sprint-backlogs/by-key/{key}", "web-1").header("Authorization", "Bearer " + token))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(id))
                .andExpect(jsonPath("$.taskKey").value("WEB-1"));
        mvc.perform(get("/api/sprint-backlogs/by-key/{key}", "WEB-999").header("Authorization", "Bearer " + token))
                .andExpect(status().isNotFound());
        mvc.perform(get("/api/sprint-backlogs/by-key/{key}", "not-a-key").header("Authorization", "Bearer " + token))
                .andExpect(status().isNotFound());
    }

    @Test
    void theKeyIsPartOfTheBacklogSearch() throws Exception {
        create(Map.of("title", "First"));
        long second = create(Map.of("title", "Second")).get("id").asLong();

        mvc.perform(get("/api/sprint-backlogs").param("search", "web-2")
                        .param("projectId", String.valueOf(projectId)).header("Authorization", "Bearer " + token))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.content.length()").value(1))
                .andExpect(jsonPath("$.content[0].id").value(second));
    }

    @Test
    void statusChangesDoNotTouchTheKey() throws Exception {
        long id = create(Map.of()).get("id").asLong();
        mvc.perform(put("/api/sprint-backlogs/{id}", id)
                        .header("Authorization", "Bearer " + token).contentType(MediaType.APPLICATION_JSON)
                        .content(json.writeValueAsString(Map.of("status", SprintBacklogStatus.TODO.name(), "isActive", true))))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.taskKey").value("WEB-1"));
    }

    @Test
    void concurrentReservationsNeverHandOutTheSameNumber() throws Exception {
        int threads = 20;
        Set<Long> numbers = ConcurrentHashMap.newKeySet();
        CountDownLatch start = new CountDownLatch(1);
        ExecutorService pool = Executors.newFixedThreadPool(threads);
        try {
            for (int index = 0; index < threads; index++) {
                pool.submit(() -> {
                    start.await();
                    numbers.add(allocator.allocate(tenantId, "RACE", 1));
                    return null;
                });
            }
            start.countDown();
            pool.shutdown();
            assertThat(pool.awaitTermination(30, TimeUnit.SECONDS)).isTrue();
        } finally {
            pool.shutdownNow();
        }
        assertThat(numbers).hasSize(threads).allMatch(number -> number >= 1 && number <= threads);
    }

    @Test
    void blockReservationsAreConsecutive() {
        assertThat(allocator.allocate(tenantId, "BLK", 5)).isEqualTo(1L);
        assertThat(allocator.allocate(tenantId, "BLK", 1)).isEqualTo(6L);
    }

    @Test
    void itemsSavedWithoutAKeyAreBackfilledWithTheNextNumber() throws Exception {
        create(Map.of());
        Long id = unkeyedItem();
        assertThat(backlogs.findById(id).orElseThrow().getTaskKey()).isNull();

        taskKeys.backfillMissing();

        SprintBacklog item = backlogs.findById(id).orElseThrow();
        assertThat(item.getTaskKey()).isEqualTo("WEB-2");
        assertThat(item.getTenantId()).isEqualTo(tenantId);
        assertThat(item.getVersion()).isZero();
    }

    @Test
    void legacyBackfillKeepsTheKeyTheScreensShowedAndMovesTheCounterPastIt() throws Exception {
        Long id = unkeyedItem();

        taskKeys.backfillLegacy();

        assertThat(backlogs.findById(id).orElseThrow().getTaskKey()).isEqualTo("WEB-" + id);
        assertThat(create(Map.of()).get("taskKey").asText()).isEqualTo("WEB-" + (id + 1));
    }

    @Test
    void legacyBackfillFallsBackToANewNumberWhenTheOldKeyIsTaken() throws Exception {
        long blocker = create(Map.of()).get("id").asLong();
        Long id = unkeyedItem();
        // Another item already owns the key the legacy rule would give (WEB-<id>).
        jdbc.update("UPDATE sprint_backlog SET task_key = ? WHERE sprint_backlog_id = ?", "WEB-" + id, blocker);

        taskKeys.backfillLegacy();

        assertThat(backlogs.findById(id).orElseThrow().getTaskKey()).startsWith("WEB-").isNotEqualTo("WEB-" + id);
    }

    @Test
    void startupMigrationGivesWorkspacesWithoutPrefixTheAcronymTheyDisplayed() throws Exception {
        jdbc.update("UPDATE workspaces SET task_key_prefix = NULL WHERE id = ?", workspaceId);

        migration.run();

        assertThat(workspaces.findById(workspaceId).orElseThrow().getTaskKeyPrefix()).isEqualTo("WS");
    }

    @Test
    void planningAndTeamBoardsExposeTheStoredKey() throws Exception {
        create(Map.of("title", "On the board"));
        String board = mvc.perform(get("/api/teams/{teamId}/backlog-board", workspaceTeamId)
                        .param("workspaceId", String.valueOf(workspaceId))
                        .header("Authorization", "Bearer " + token))
                .andExpect(status().isOk()).andReturn().getResponse().getContentAsString();
        List<String> keys = json.readTree(board).findValuesAsText("taskKey");
        assertThat(keys).contains("WEB-1");
    }
}
