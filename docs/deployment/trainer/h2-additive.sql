CREATE TABLE IF NOT EXISTS trainers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    created_by BIGINT,
    updated_at TIMESTAMP(6) NOT NULL,
    updated_by BIGINT,
    trainer_code VARCHAR(50) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    specialization VARCHAR(500),
    status ENUM('ACTIVE','INACTIVE') NOT NULL,
    CONSTRAINT uk_trainer_code UNIQUE(trainer_code),
    CONSTRAINT uk_trainer_email UNIQUE(email)
);
CREATE TABLE IF NOT EXISTS trainer_teaching_topics (
    subject_id BIGINT NOT NULL,
    trainer_id BIGINT NOT NULL,
    PRIMARY KEY(subject_id, trainer_id),
    CONSTRAINT fk_trainer_topic_subject FOREIGN KEY(subject_id) REFERENCES subjects(id),
    CONSTRAINT fk_trainer_topic_trainer FOREIGN KEY(trainer_id) REFERENCES trainers(id)
);
ALTER TABLE training_operation_classes ADD COLUMN IF NOT EXISTS master_trainer_id BIGINT;
ALTER TABLE teaching_assignments ADD COLUMN IF NOT EXISTS trainer_source VARCHAR(20);
